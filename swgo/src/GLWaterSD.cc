G4bool GLWaterSD::ProcessHits(G4Step *aStep, G4TouchableHistory *) {
    if (aStep->GetTrack()->GetDefinition() == G4OpticalPhoton::OpticalPhotonDefinition()) return false;

    // G4int eventID = G4RunManager::GetRunManager()->GetCurrentEvent();
    // G4double fTotalEdep;

    // for particles
    G4ParticleDefinition *particleType = aStep->GetTrack()->GetDefinition();
    G4String particleName = particleType->GetParticleName();
    // G4double edep = aStep->GetTotalEnergyDeposit();
    //  fTotalEdep += edep;
    G4StepPoint *startPoint = aStep->GetPreStepPoint();
    G4StepPoint *endPoint = aStep->GetPostStepPoint();

    G4double fGlobalTime = startPoint->GetGlobalTime();

    //  G4StepPoint *startPoint = aStep->GetPreStepPoint();
    G4double E0 = startPoint->GetKineticEnergy();
    G4double edep = aStep->GetTotalEnergyDeposit();
    // G4double E1 = E0 - edep;
    // G4double E2 = endPoint->GetKineticEnergy();
    // G4double etrans = E1 - E2;
    // G4double lgepsE = 0.;
    // if (etrans > 0.) lgepsE = std::log10(etrans / E1);

    G4ThreeVector posParticle = endPoint->GetPosition();
    G4ThreeVector momParticle = startPoint->GetMomentum();
    G4double fMomMag = momParticle.mag();

    // Foton mom
    // G4double FWlen = (1.23981939 * CLHEP::eV/m);

    G4double stepl = 0.;
    if (particleType->GetPDGCharge() != 0.)
        stepl = aStep->GetStepLength();

    if ((edep == 0.) && (stepl == 0.)) return false;

    G4AnalysisManager *analysisManager = G4AnalysisManager::Instance();

    // analysisManager->FillNtupleDColumn(0, 1, posParticle[0]);
    // analysisManager->FillNtupleDColumn(0, 2, posParticle[1]);
    // analysisManager->FillNtupleDColumn(0, 3, posParticle[2]);
    // analysisManager->FillNtupleDColumn(0, 4, fGlobalTime);
    // analysisManager->AddNtupleRow(0);

    // secondaries
    const std::vector<const G4Track *> *secondary = aStep->GetSecondaryInCurrentStep();
    size_t size_secondary = (*secondary).size();
    G4String secondaryname = "";
    G4String process = "";
    std::vector<G4double> secondaryenergy_electron;
    std::vector<G4int> secondarynumber_electron;
    // std::vector<G4double> secondaryenergy_cerenkov;
    G4double secondaryTotalenergy_cerenkov;
    std::vector<G4double> temp;

    G4int counter = 0;
    G4int fNumberSecondary = aStep->GetNumberOfSecondariesInCurrentStep();

    // eletrons
    G4double secondaryenergy_electron_sum = 0.;
    G4double secondaryelectron_count = 0.;

    // cerenkov photons
    G4double secondaryenergy_cerenkov_sum = 0.;
    G4double secondarycerenkov_count = 0.;
    G4double secondarycerenkov_electron_count = 0.;
    G4double secondarycerenkov_muon_count = 0.;

    // by scintillation test
    G4double secondaryenergy_scintillation_sum = 0.;
    G4double secondaryscintillation_count = 0.;
    G4double secondaryscintillation_electron_count = 0.;
    G4double secondaryscintillation_muon_count = 0.;

    for (size_t i = 0; i < (*secondary).size(); i++) {
        // auto secstep = (*secondary)[i];
        // auto element = ((secstep->GetCreatorProcess()->GetProcessName()=="Cerenkov"));
        // auto secEkin = secstep->GetKineticEnergy();
        // auto trackID = aStep->GetTrack()->GetTrackID();
        secondaryname = (*secondary)[i]->GetDefinition()->GetParticleName();
        process = (*secondary)[i]->GetCreatorProcess()->GetProcessName();

        // Electrons generated by mu process(muIoni): Ekin, e- count
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "e-" and aStep->GetTrack()->GetParentID() == 0) {
            //  secondaryname_e = (*secondary)[i]->GetDefinition()->GetParticleName(); //e- ok
            //  process_e = (*secondary)[i]->GetCreatorProcess()->GetProcessName();  //muIoni

            secondaryenergy_electron_sum += (*secondary)[i]->GetKineticEnergy();
            secondaryelectron_count++;

            //   G4cout << secondaryname << process << secondaryenergy_electron_sum / CLHEP::eV << secondaryelectron_count << G4endl;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Cerenkov") {
            secondaryenergy_cerenkov_sum += (*secondary)[i]->GetKineticEnergy();
            secondarycerenkov_count++;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Scintillation") {
            secondaryenergy_scintillation_sum += (*secondary)[i]->GetKineticEnergy();
            secondaryscintillation_count++;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Cerenkov" and aStep->GetTrack()->GetParentID() == 0) {
            secondarycerenkov_muon_count++;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Scintillation" and aStep->GetTrack()->GetParentID() == 0) {
            secondaryscintillation_muon_count++;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Cerenkov" and aStep->GetTrack()->GetParentID() == 1) {
            secondarycerenkov_electron_count++;
        }
        if ((*secondary)[i]->GetDefinition()->GetParticleName() == "opticalphoton" and (*secondary)[i]->GetCreatorProcess()->GetProcessName() == "Scintillation" and aStep->GetTrack()->GetParentID() == 1) {
            secondaryscintillation_electron_count++;
        }
    }

    G4TouchableHistory *theTouchable =
        (G4TouchableHistory *)(aStep->GetPreStepPoint()->GetTouchable());
    // G4VPhysicalVolume* thePrePV = theTouchable->GetVolume();
    G4StepPoint *thePostPoint = aStep->GetPostStepPoint();

    // Get the average position of the hit
    G4ThreeVector pos = endPoint->GetPosition() + thePostPoint->GetPosition();
    pos /= 2.;

    // G4cout << "Particle type: " << particleName << G4endl;
    // G4cout << "Particle time: " << aStep->GetPreStepPoint()->GetGlobalTime() / CLHEP::nanosecond << G4endl;

    GLWaterHit *scintHit = new GLWaterHit();

    // scintHit->SetEdep(lgepsE);
    // scintHit->SetEdep(edep);
    scintHit->SetEdep(edep);
    scintHit->SetNumberSecondary(fNumberSecondary);
    scintHit->SetTime(aStep->GetPreStepPoint()->GetGlobalTime());
    scintHit->SetPos(pos);
    scintHit->SetParticle(particleName);
    scintHit->SetSecondaryParticle(secondaryname);
    scintHit->SetParticleProcess(process);

    scintHit->SetSecondaryElectronEnergy(secondaryenergy_electron_sum);
    scintHit->SetSecondaryElectronCount(secondaryelectron_count);

    scintHit->SetSecondaryCerenkovEnergy(secondaryenergy_cerenkov_sum);
    scintHit->SetSecondaryCerenkovCount(secondarycerenkov_count);
    scintHit->SetSecondaryCerenkovMuonCount(secondarycerenkov_muon_count);
    scintHit->SetSecondaryCerenkovElectronCount(secondarycerenkov_electron_count);

    // optical prop test for water
    scintHit->SetSecondaryScintillationEnergy(secondaryenergy_scintillation_sum);
    scintHit->SetSecondaryScintillationCount(secondaryscintillation_count);
    scintHit->SetSecondaryScintillationMuonCount(secondaryscintillation_muon_count);
    scintHit->SetSecondaryScintillationElectronCount(secondaryscintillation_electron_count);

    fWaterCollection->insert(scintHit);

    return true;
}

void GLWaterSD::EndOfEvent(G4HCofThisEvent *hitsCE) {

    G4String HCname = collectionName[0];
    static G4int HCID = -1;
    if (HCID < 0)
        HCID = G4SDManager::GetSDMpointer()->GetCollectionID(HCname);
    hitsCE->AddHitsCollection(HCID, fWaterCollection);

    G4int nHits = fWaterCollection->entries();
    if (verboseLevel >= 1)
        G4cout << "     Water collection: " << nHits << " hits" << G4endl;
    if (verboseLevel >= 2)
        fWaterCollection->PrintAllHits();
}

