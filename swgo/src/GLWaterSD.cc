GLWaterSD::GLWaterSD(G4String name)
    : G4VSensitiveDetector(name), fHitsCID(-1) {
    fWaterCollection = nullptr;
    collectionName.insert("waterCollection");
}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

GLWaterSD::~GLWaterSD() {}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void GLWaterSD::Initialize(G4HCofThisEvent *hitsCE) {
    fWaterCollection =
        new GLWaterHitsCollection(SensitiveDetectorName, collectionName[0]);

    if (fHitsCID < 0) {
        fHitsCID = G4SDManager::GetSDMpointer()->GetCollectionID(fWaterCollection);
    }
    hitsCE->AddHitsCollection(fHitsCID, fWaterCollection);
}

